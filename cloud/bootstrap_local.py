"""One-time authorized bootstrap; never distributed with the desktop app.
Reads an export generated by the maintenance harness. The temporary bootstrap
session is created through the admin SQL tool and revoked immediately after upload.
"""
import collections, hashlib, json, pathlib, secrets, sys, urllib.request
path = pathlib.Path(sys.argv[2])
data = json.loads(path.read_text(encoding='utf-8-sig'))
base = 'https://efekzvmgnicztweluyim.supabase.co/functions/v1/fredi-api/'
def quote(value): return "'" + str(value).replace("'", "''") + "'"
if sys.argv[1] == '--seed':
    admin = next(json.loads(p['Payload']) for p in data['Pending'] if p['Scope']=='admin')
    master = next(r['Data'] for r in admin['Records'] if r['Table']=='LocalUser' and r['Data']['Id']==data['UserId'])
    token = secrets.token_hex(32); token_hash = hashlib.sha256(token.encode()).hexdigest()
    path.with_suffix('.token').write_text(token)
    sql = 'begin;\n'
    sql += 'insert into public.fredi_users(dataset,id,username,payload) values (%s,%d,%s,%s::jsonb);\n' % (quote(data['Dataset']),master['Id'],quote(master['Username']),quote(json.dumps(master)))
    sql += 'insert into public.fredi_sessions(token_hash,dataset,user_id,security_version,expires_at) values (%s,%s,%d,%d,now()+interval \'15 minutes\');\ncommit;' % (quote(token_hash),quote(data['Dataset']),data['UserId'],data['Version'])
    path.with_suffix('.sql').write_text(sql)
    print('Bootstrap seed prepared without exposing credentials.')
else:
    token = path.with_suffix('.token').read_text(); acks=[]
    counts=collections.Counter()
    try:
        for p in data['Pending']:
            req=urllib.request.Request(base+'v1/sync', p['Payload'].encode(), {'Content-Type':'application/json','Authorization':'Bearer '+token})
            with urllib.request.urlopen(req,timeout=60) as response: result=json.load(response)
            assert result['requestId']==p['RequestId']
            acks.append({'Scope':p['Scope'],'RequestId':p['RequestId'],'Revision':result['revision']})
            path.with_suffix('.acks.json').write_text(json.dumps(acks))
            counts.update(r['Table'] for r in json.loads(p['Payload'])['Records'])
        print('Confirmed groups:',len(acks)); print('Cloud record counts:',dict(counts))
    finally:
        req=urllib.request.Request(base+'v1/auth/logout', b'{}', {'Content-Type':'application/json','Authorization':'Bearer '+token})
        with urllib.request.urlopen(req,timeout=15) as response: print('Bootstrap session revoked:',response.status==200)
